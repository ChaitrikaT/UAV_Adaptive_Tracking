"""Generate readable, evidence-labelled reports from historical CSV measurements."""
from __future__ import annotations

from html import escape
import hashlib
import json
from pathlib import Path


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def _fmt(value):
    if isinstance(value, float):
        return f'{value:.3f}'
    return str(value)


def write_report(out_dir: Path, results: dict, files: dict[str, Path | None]) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for name, path in files.items():
        if path is not None and path.is_file():
            manifest[name] = {'path': str(path), 'sha256': sha256(path), 'size_bytes': path.stat().st_size}
    report = {**results, 'input_manifest': manifest}
    (out_dir / 'research_metrics.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    lines = [
        '# Offline Research Evaluation Report', '',
        '**Scope:** Retrospective analysis of previously saved detector and selector outcomes.',
        '**Not demonstrated:** live camera processing, online mode switching, autonomous tracking, or tracking FPS.', '',
    ]
    section = report['selector_review']
    if section is not None:
        lines += ['## FAST / ROBUST / selector replay', '',
                  f'- Evaluated Clip: {section["evaluation_clip"]}',
                  f'- Sampled still frames: {section["sampled_frames"]}',
                  f'- Selected mode counts: {section["mode_counts"]}', '',
                  '| Policy | TP | FP | FN | Precision | Recall | F1 | Mean model latency (ms) |',
                  '|---|---:|---:|---:|---:|---:|---:|---:|']
        for key, v in section['comparison'].items():
            lines.append(f'| {key} | {v["TP"]} | {v["FP"]} | {v["FN"]} | '
                         f'{v["precision_iou50"]:.3f} | {v["recall_iou50"]:.3f} | '
                         f'{v["f1_iou50"]:.3f} | {v["mean_model_call_latency_ms"]:.3f} |')
        lines += ['', '### Interpretation', '',
                  f'- Learned selector recall exceeds always ROBUST: **{section["learned_better_recall_than_robust"]}**',
                  f'- Learned selector model-call latency is below always ROBUST: **{section["learned_lower_model_latency_than_robust"]}**',
                  '- These are model-call timings only; detector call overhead and end-to-end video speed are not measured.',
                  '- Quality columns use an IoU=0.5 matching convention, not HOTA, MOTA, or IDF1.',
                  '- The selector validation clip is not necessarily an untouched detector test clip.', '']
    else:
        lines += ['## Selector replay', '', 'Not evaluated: paired benchmark and/or decision CSV unavailable.', '']
    timeline = report.get('timeline_review')
    if timeline:
        lines += ['## Video-to-conditions analysis (recorded frames)', '',
                  f'- Frames: {timeline["frames"]}',
                  f'- Matched frames: {timeline["matched_frames"]}',
                  f'- Longest unmatched interval: {timeline["longest_consecutive_unmatched_frames"]} frames '
                  f'({timeline["longest_unmatched_start_frame"]} to {timeline["longest_unmatched_end_frame"]})',
                  '- Detailed frame join: `timeline_review.csv`',
                  '- IoU is computed using reference boxes after inference and is never a mode-selection input.', '']
    tracks = report['track_review']
    if tracks:
        lines += ['## Saved track ID audit (optional)', '']
        for k,v in tracks.items():
            lines.append(f'- {k}: {v}')
        lines += ['', 'Saved predictions were evaluated retrospectively. No track IDs were generated by this add-on.', '']
    else:
        lines += ['## Saved track ID audit', '',
                  'Not performed: no independently generated prediction CSV and reference annotations were supplied.', '']
    lines += ['## Reproducibility', '', 'Input SHA-256 hashes are saved in `research_metrics.json`.', '',
              '## Limitations', '',
              '- The dataset frames are temporally related; a clip split is not automatically a flight-independent split.',
              '- Confidence and IoU settings must match before comparing reported values.',
              '- A weaker learned policy should be reported, not hidden or described as successful adaptation.',
              '- No results in this report establish an integrated airborne target-tracking system.', '']
    (out_dir / 'research_report.md').write_text('\n'.join(lines), encoding='utf-8')

    html_rows = ''
    if section:
        for key, v in section['comparison'].items():
            cells = [key, v['TP'], v['FP'], v['FN'], f"{v['precision_iou50']:.3f}",
                     f"{v['recall_iou50']:.3f}", f"{v['f1_iou50']:.3f}",
                     f"{v['mean_model_call_latency_ms']:.3f}"]
            html_rows += '<tr>' + ''.join('<td>' + escape(str(cell)) + '</td>' for cell in cells) + '</tr>\n'
    else:
        html_rows = '<tr><td colspan="8">No saved benchmark + selector replay available</td></tr>'
    tracktext = ('No independently generated tracking CSV supplied. Identity tracking not assessed.'
                 if not tracks else json.dumps(tracks, indent=2))
    timeline_text = ('No matched video diagnostic/condition records supplied.' if not report.get('timeline_review')
                     else json.dumps(report['timeline_review'], indent=2))
    html_doc = '''<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Offline Research Review</title>
<style>body{font:16px system-ui,sans-serif;max-width:960px;margin:38px auto;padding:0 18px;color:#243143;background:#fafbfc}h1,h2{color:#19263b}table{border-collapse:collapse;width:100%;background:white}th,td{border-bottom:1px solid #dde4eb;padding:10px;text-align:right}th:first-child,td:first-child{text-align:left}.note{padding:14px;border-left:4px solid #8799ad;background:#f0f3f7}pre{white-space:pre-wrap;overflow-wrap:anywhere}</style></head>
<body><h1>Offline perception research review</h1><p class="note">Recorded measurements only. No online mode switching, video FPS, or independently predicted UAV tracking is claimed.</p>
<h2>Paired detector modes and saved selector decisions</h2><table><thead><tr><th>Policy</th><th>TP</th><th>FP</th><th>FN</th><th>Precision</th><th>Recall</th><th>F1</th><th>Mean latency (ms)</th></tr></thead><tbody>''' + html_rows + '''</tbody></table><p>Model-call latency excludes image decoding, feature extraction, tracking and switching overhead.</p>
<h2>Recorded video condition analysis</h2><pre>''' + escape(timeline_text) + '''</pre><h2>Tracking evidence</h2><pre>''' + escape(tracktext) + '''</pre><h2>Methodological cautions</h2><p>Training and evaluation must be separated by video sequence. Selector evaluation clips may still have informed earlier detector validation. This viewer summarizes pre-recorded evidence; it does not run detectors or trackers.</p></body></html>'''
    (out_dir / 'index.html').write_text(html_doc, encoding='utf-8')
